import { readFileSync, writeFileSync } from "node:fs";
const set = JSON.parse(readFileSync("node_modules/@iconify-json/solar/icons.json", "utf8"));
// IconName -> solar base name. "-outline" for rest state, "-bold" for filled/active.
const MAP = {
  home: "home-smile", compass: "magnifer", bag: "bag", plus: "add-circle",
  message: "chat-line", bell: "bell", user: "user", heart: "heart",
  bookmark: "bookmark", share: "share", volumeOn: "volume-loud",
  volumeOff: "volume-cross", chevronRight: "alt-arrow-right",
  chevronDown: "alt-arrow-down", music: "music-note", check: "check-read", play: "play",
  school: "square-academic-cap", back: "alt-arrow-left",
};
const out = {}, missing = [];
for (const [k, base] of Object.entries(MAP)) {
  const o = set.icons[`${base}-outline`], b = set.icons[`${base}-bold`];
  if (!o) missing.push(`${base}-outline`);
  if (!b) missing.push(`${base}-bold`);
  if (o && b) out[k] = { o: o.body, b: b.body };
}
if (missing.length) { console.error("MISSING:", missing.join(", ")); process.exit(1); }
writeFileSync(
  "components/ui/solar-icons.generated.ts",
  "// Generated by scripts/gen-solar.mjs from @iconify-json/solar. Do not edit.\n" +
  "export const SOLAR: Record<string, { o: string; b: string }> = " + JSON.stringify(out, null, 2) + ";\n",
);
console.log("ok:", Object.keys(out).length, "icons");
