// Builds lib/icons/solar-data.ts from @iconify-json/solar. Run: node scripts/gen-icons.mjs
import fs from "node:fs";
import path from "node:path";

const json = JSON.parse(
  fs.readFileSync(path.join(process.cwd(), "node_modules/@iconify-json/solar/icons.json"), "utf8"),
);

// App icon name -> Solar name stems, first one that exists wins. Flutter equivalents in comments.
const MAP = {
  home: ["home-smile"], // homeSmile
  compass: ["magnifer"], // magnifier (Discover tab); Iconify spells it "magnifer"
  search: ["magnifer"],
  bag: ["bag-2"], // bag2
  plus: ["add", "add-circle"],
  message: ["chat-line"], // chatLine
  bell: ["bell"],
  user: ["user"],
  userPlus: ["user-plus-rounded"], // userPlusRounded
  heart: ["heart"],
  bookmark: ["bookmark"],
  share: ["share", "forward"],
  repeat: ["repeat"],
  dots: ["menu-dots"], // menuDots
  volumeOn: ["volume-loud"],
  volumeOff: ["volume-cross", "volume-small"],
  chevronRight: ["alt-arrow-right"],
  chevronDown: ["alt-arrow-down"],
  back: ["alt-arrow-left"],
  music: ["music-note"], // musicNote
  check: ["check", "check-circle"],
  close: ["close", "close-circle"],
  play: ["play"],
  school: ["square-academic-cap", "book"],
  link: ["link"],
  trash: ["trash-bin-2"], // trashBin2
  send: ["plain"], // plain (send)
  eye: ["eye"],
  edit: ["pen-2"], // pen2
};

function resolve(name) {
  let e = json.icons[name];
  if (!e && json.aliases?.[name]) e = json.icons[json.aliases[name].parent];
  return e ? { body: e.body, w: e.width ?? json.width ?? 24, h: e.height ?? json.height ?? 24 } : null;
}

const out = {};
const problems = [];
for (const [key, stems] of Object.entries(MAP)) {
  out[key] = {};
  for (const variant of ["linear", "bold"]) {
    let hit = null;
    let used = "";
    for (const s of stems) {
      hit = resolve(`${s}-${variant}`);
      if (hit) {
        used = `${s}-${variant}`;
        break;
      }
    }
    if (!hit) {
      const word = stems[0].split("-")[0];
      const near = Object.keys(json.icons).filter((n) => n.includes(word) && n.endsWith(variant)).slice(0, 8);
      problems.push(`${key}/${variant}: none of [${stems.join(", ")}] exist. Close: ${near.join(", ") || "(none)"}`);
      continue;
    }
    if (hit.w !== 24 || hit.h !== 24) problems.push(`${key}/${variant}: ${used} is ${hit.w}x${hit.h}, expected 24x24`);
    out[key][variant] = hit.body;
    console.log(`${key.padEnd(13)} ${variant.padEnd(6)} -> ${used}`);
  }
}
if (problems.length) {
  console.error("\nPROBLEMS:\n" + problems.join("\n"));
  process.exit(1);
}

const names = Object.keys(MAP);
fs.writeFileSync(
  path.join(process.cwd(), "lib/icons/solar-data.ts"),
  `// GENERATED by scripts/gen-icons.mjs from @iconify-json/solar. Do not edit by hand.\n` +
    `export type IconName =\n  | ${names.map((n) => JSON.stringify(n)).join("\n  | ")};\n\n` +
    `export const SOLAR_ICONS: Record<IconName, { linear: string; bold: string }> = ${JSON.stringify(out, null, 2)};\n`,
);
console.log(`\nWrote lib/icons/solar-data.ts (${names.length} icons)`);
